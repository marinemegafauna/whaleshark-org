import { afterEach, beforeEach, expect, test, vi } from 'vitest';
import { env } from 'cloudflare:workers';
import { matchingStore } from '../../../lib/runtime';
import { buildBatchFromCascadeReport } from '../../../lib/match-batch';
import { createMemoryStore } from '../../../lib/db';
import { POST as verdict } from './[batch]/verdict';
import { POST as hydrate } from './[batch]/cards/[enc]/hydrate';
import { GET as photo } from './photo';
import { GET as decisions } from './[batch]/decisions.json';
import { POST as review } from '../review';
import { POST as scars } from '../scars';
const worker=env as Record<string,unknown>;
const batch=buildBatchFromCascadeReport({thresholds:{likely_score:.45,likely_margin:.1,possible_score:.4,possible_margin:.05,duplicate_suspect:.99},results:[{query_enc:'test-query',class:'likely',cand_key:'A',cand_name:'A',cand_enc:'test-candidate',s1:.6}]},{id:'route-tests',title:'Synthetic route tests',site:'kenya'});
beforeEach(async()=>{worker.MOCK_APP='1';createMemoryStore().reset();await matchingStore({} as App.Locals).importBatch(batch);});
afterEach(()=>{delete worker.MOCK_APP;delete worker.SCAR_WRITEBACK;vi.unstubAllGlobals();});
const post=(body:unknown)=>verdict({request:new Request('http://local/api/matching/route-tests/verdict',{method:'POST',body:JSON.stringify(body)}),params:{batch:batch.id},locals:{}} as never);
test('verdict validates card/candidate, persists labels/reviewer, clears and exports',async()=>{
  expect((await post({query_enc:'missing',verdict:'new'})).status).toBe(404);
  expect((await post({query_enc:'test-query',verdict:'invalid'})).status).toBe(400);
  expect((await post({query_enc:'test-query',verdict:'same',candidate_key:'invalid'})).status).toBe(400);
  const response=await post({query_enc:'test-query',verdict:'same',candidate_key:'A',notes:'Review',scar_notes:'Quick'});
  expect(await response.json()).toMatchObject({ok:true,verdict:{candidate_label:'A',reviewer:'local'}});
  const exported=await decisions({params:{batch:batch.id},locals:{}} as never);
  expect(exported.headers.get('Content-Disposition')).toContain('route-tests.decisions.json');
  expect(((await exported.json()) as {verdicts:Record<string,unknown>}).verdicts['test-query']).toMatchObject({candidate:'A',candidate_enc:'test-candidate',scars:'Quick'});
  await post({query_enc:'test-query',verdict:''});
  expect(await matchingStore({} as App.Locals).getVerdicts(batch.id)).toEqual([]);
});
test('proxy sends no cookie, rejects redirects/nonimages, streams image and cache headers',async()=>{
  const fetcher=vi.fn(async()=>new Response('image',{headers:{'Content-Type':'image/jpeg'}}));vi.stubGlobal('fetch',fetcher);
  const url=new URL('http://local/api/matching/photo');url.searchParams.set('u','https://www.sharkbook.ai/wildbook_data_dir/test/image.jpg');
  const response=await photo({url} as never);
  expect(response.status).toBe(200);expect(await response.text()).toBe('image');
  expect(response.headers.get('Cache-Control')).toBe('private, max-age=604800');
  expect(fetcher.mock.calls[0]).toEqual([new URL(url.searchParams.get('u')!),{redirect:'manual'}]);
  fetcher.mockImplementation(async()=>new Response('',{status:302,headers:{Location:'https://evil.test'}}));
  expect((await photo({url} as never)).status).toBe(502);
  fetcher.mockImplementation(async()=>new Response('html',{headers:{'Content-Type':'text/html'}}));
  expect((await photo({url} as never)).status).toBe(502);
});
test('hydrate mock fallback and expired-session response',async()=>{
  const context={params:{batch:batch.id,enc:'test-query'},locals:{session:{wildbook_cookie:'test-cookie'}},url:new URL('http://local?refresh=1'),cookies:{delete:vi.fn()}};
  expect(await (await hydrate(context as never)).json()).toMatchObject({ok:true,photos:0});
  worker.MOCK_APP='0';vi.stubGlobal('fetch',async()=>new Response('',{status:401}));
  const response=await hydrate(context as never);
  expect(response.status).toBe(401);expect(await response.json()).toEqual({ok:false,error:'expired'});
  expect(context.cookies.delete).toHaveBeenCalledWith('whaleshark_session',{path:'/'});
});
const redirect=(location:string,status=303)=>new Response(null,{status,headers:{Location:location}});
const formContext=(body:FormData)=>({request:new Request('http://local',{method:'POST',body}),locals:{},redirect,cookies:{delete(){}}});
test('scar/review forms preserve safe matching returns, finishing returns and matching suppresses writeback',async()=>{
  const body=new FormData();body.set('encounter_id','test-query');body.set('site_id','kenya');body.set('return','/app/matching/route-tests?card=1');
  worker.SCAR_WRITEBACK='append';
  const saved=await scars(formContext(body) as never);
  expect(saved.headers.get('Location')).toContain('return=%2Fapp%2Fmatching');
  expect((await createMemoryStore().listScarRecords({encounterId:'test-query'}))[0].sync_status).toBe('disabled');
  body.set('status','recorded');
  expect((await review(formContext(body) as never)).headers.get('Location')).toBe('/app/matching/route-tests?card=1');
  body.set('status','examined_clean');
  expect((await review(formContext(body) as never)).headers.get('Location')).toContain('return=%2Fapp%2Fmatching');
  body.set('return','https://evil.test');body.set('status','not_examined');
  expect((await review(formContext(body) as never)).headers.get('Location')).not.toContain('evil.test');
});
